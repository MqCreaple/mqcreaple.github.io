// scripts/vite-plugin-worklet.mjs
// Compile TypeScript AudioWorklet sources at build/dev time so the worklet can
// be loaded straight from its `.worklet.ts` file:
//
//   import workletUrl from '../dynamics/lorenz.worklet.ts?worklet';
//   await audioContext.audioWorklet.addModule(workletUrl);
//
// The `?worklet` import is resolved to the real `.worklet.ts` file with the
// query preserved; `load()` then transpiles that file to plain JavaScript with
// esbuild and exports a same-origin Blob URL containing the script.
// `audioWorklet.addModule()` fetches the Blob exactly like any other
// same-origin module script, so no hand-compiled copy has to be kept next to
// the TypeScript source.
//
// Note: with Rolldown (Vite 8+) the native resolver resolves `./x.worklet.ts`
// plus its `?worklet` query without consulting JS `resolveId` hooks, so the
// interception happens in `load()` for both dev and production builds.

import { readFile } from 'node:fs/promises';
import { transformWithOxc } from 'vite';

const WORKLET_QUERY = '?worklet';

/** Vite/Astro plugin that bundles `*.worklet.ts?worklet` imports as Blob URLs. */
export default function vitePluginWorklet() {
  return {
    name: 'vite-plugin-worklet',

    // Classic (dev) resolution: keep the query on the resolved file id so the
    // module graph and `load()` below see `.../lorenz.worklet.ts?worklet`.
    async resolveId(source, importer) {
      if (!source.includes(WORKLET_QUERY)) return null;
      const [file] = source.split('?');
      const resolved = await this.resolve(file, importer, { skipSelf: true });
      if (!resolved) {
        throw new Error(
          `vite-plugin-worklet: cannot resolve "${source}" from "${importer ?? ''}"`,
        );
      }
      return resolved.id + WORKLET_QUERY;
    },

    async load(id) {
      const queryIndex = id.lastIndexOf(WORKLET_QUERY);
      if (queryIndex === -1) return null;
      const file = id.slice(0, queryIndex);
      if (!file.endsWith('.worklet.ts') && !file.endsWith('.worklet.js')) return null;

      const code = await readFile(file, 'utf8');
      const result = await transformWithOxc(code, file, { lang: 'ts' });
      return [
        '// Generated by vite-plugin-worklet: TypeScript AudioWorklet compiled to a Blob URL.',
        `const workletCode = ${JSON.stringify(result.code)};`,
        "const workletBlob = new Blob([workletCode], { type: 'text/javascript' });",
        'const workletUrl = URL.createObjectURL(workletBlob);',
        'export default workletUrl;',
        '',
      ].join('\n');
    },
  };
}